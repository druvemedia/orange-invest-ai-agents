"""Report view: citation resolution and readable evidence lines."""

import asyncio

import pytest

from app.agents import AgentConfig, OrchestratorAgent
from app.llm import ScriptedLLMClient
from app.product.report_view import _Resolver, build_view, describe
from app.product.sources import load_sources
from tests import agent_scripts as s

SOURCES = load_sources()


@pytest.fixture(scope="module")
def result():
    demo = SOURCES["demo"]
    incident = next(e for e in demo.examples if e.incident_id == "INC-2041")
    return asyncio.run(OrchestratorAgent(ScriptedLLMClient(s.full_script()), demo.tools(), AgentConfig()).investigate(incident))


@pytest.mark.parametrize(
    ("record", "expected"),
    [
        ({"timestamp": "T", "service": "a", "level": "ERROR", "message": "boom"}, "T a ERROR: boom"),
        ({"timestamp": "T", "service": "a", "metric_name": "lat", "value": 12.0, "unit": "ms"}, "T a lat = 12 ms"),
        ({"timestamp": "T", "change_id": "C1", "service": "a", "change_type": "config_change", "status": "succeeded",
          "summary": "Pool", "details": {"k": "v"}}, 'T C1 a config_change (succeeded): Pool {"k": "v"}'),
        ({"service": "a", "depends_on": "b", "dependency_type": "http", "critical": True}, "a depends on b (http, critical)"),
        ({"incident_id": "H1", "title": "T", "occurred_at": "2026-01-01T00:00:00Z", "root_cause": None},
         "Past incident H1 (2026-01-01): T. Root cause not recorded."),
    ],
)
def test_records_are_described_readably(record, expected):
    assert describe(record) == expected


def test_resolver_follows_findings_and_flags_unknown_refs(result):
    resolver = _Resolver(result.investigation.tasks)

    record = resolver.one("ev.logs#0")
    finding = resolver.one("observability/obs-1")
    whole = resolver.one("ev.metrics")
    missing = resolver.one("ev.logs#999")

    assert record.kind == "record" and record.tool == "search_logs" and "fraud-check" in record.text
    assert finding.kind == "finding" and finding.based_on and all(b.kind == "record" for b in finding.based_on)
    assert whole.kind == "result" and whole.text == "query_metrics: partial, 90 record(s)"  # fraud-check coverage gap
    assert missing.kind == "unresolved" and resolver.unresolved == {"ev.logs#999"}


def test_view_lists_unresolved_citations_instead_of_hiding_them(result):
    tampered = result.model_copy(deep=True)
    tampered.report.report.ranked_hypotheses[0].supporting_refs.append("ev.invented#1")

    view = build_view(tampered, evidence_source="demo", model="test")

    assert view.unresolved_citations == ["ev.invented#1"]
    assert build_view(result, evidence_source="demo", model="test").unresolved_citations == []


